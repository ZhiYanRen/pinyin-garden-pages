// 每道题包含正确答案；选项作稳定轮换，避免正确答案固定在第一位。
function topic(id, title, subtitle, kind, color, tip, rows) {
  return {
    id, title, subtitle, kind, color, tip,
    items: rows.map(([text, pinyin, distractors, explain], index) => {
      const choices = [pinyin, ...(Array.isArray(distractors) ? distractors : [distractors])];
      const offset = index % choices.length;
      const options = [...choices.slice(offset), ...choices.slice(0, offset)];
      return { id: `${id}-${index + 1}`, text, pinyin, options, explain };
    }),
  };
}

